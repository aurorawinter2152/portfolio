function rotl(x, n){ return ((x << n) | (x >>> (32 - n))) >>> 0; }

function tau(x){
  const b0 = SBOX[(x>>>24)&0xff];
  const b1 = SBOX[(x>>>16)&0xff];
  const b2 = SBOX[(x>>>8)&0xff];
  const b3 = SBOX[x&0xff];
  return (b0<<24 | b1<<16 | b2<<8 | b3) >>> 0;
}
function L(b){ return (b ^ rotl(b,2) ^ rotl(b,10) ^ rotl(b,18) ^ rotl(b,24)) >>> 0; }
function Lprime(b){ return (b ^ rotl(b,13) ^ rotl(b,23)) >>> 0; }

export function keySchedule(key){
  const K = new Array(36);
  for(let i=0;i<4;i++){
    const k = (key[4*i]<<24 | key[4*i+1]<<16 | key[4*i+2]<<8 | key[4*i+3]) >>> 0;
    K[i] = (k ^ FK[i]) >>> 0;
  }
  const rk = new Array(32);
  for(let i=0;i<32;i++){
    const t = (K[i+1] ^ K[i+2] ^ K[i+3] ^ CK[i]) >>> 0;
    const b = tau(t);
    K[i+4] = (K[i] ^ Lprime(b)) >>> 0;
    rk[i] = K[i+4];
  }
  return rk;
}

export function sm4EncryptBlock(block, rk){
  const X = new Array(36);
  for(let i=0;i<4;i++){
    X[i] = (block[4*i]<<24 | block[4*i+1]<<16 | block[4*i+2]<<8 | block[4*i+3]) >>> 0;
  }
  for(let i=0;i<32;i++){
    X[i+4] = (X[i] ^ L(tau(X[i+1] ^ X[i+2] ^ X[i+3] ^ rk[i]))) >>> 0;
  }
  const out = new Uint8Array(16);
  const words = [X[35], X[34], X[33], X[32]];
  for(let i=0;i<4;i++){
    out[4*i]   = (words[i]>>>24)&0xff;
    out[4*i+1] = (words[i]>>>16)&0xff;
    out[4*i+2] = (words[i]>>>8)&0xff;
    out[4*i+3] = words[i]&0xff;
  }
  return out;
}

export function pkcs7Pad(data, blockSize=16){
  const pad = blockSize - (data.length % blockSize);
  const out = new Uint8Array(data.length + pad);
  out.set(data);
  out.fill(pad, data.length);
  return out;
}

export function sm4EcbEncrypt(plaintext, key){
  const rk = keySchedule(key);
  const padded = pkcs7Pad(plaintext, 16);
  const out = new Uint8Array(padded.length);
  for(let i=0;i<padded.length;i+=16){
    out.set(sm4EncryptBlock(padded.subarray(i,i+16), rk), i);
  }
  return out;
}

export function bytesToBase64(u8){
  let s = "";
  for(let i=0;i<u8.length;i++) s += String.fromCharCode(u8[i]);
  return btoa(s);
}
